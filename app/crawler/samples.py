def sample_listings(platform: str, limit: int = 200) -> list[dict]:
    """按平台取样本，返回 BaseAdapter 需要的 RawListing 字段。"""
    out = []
    for s in all_samples():
        if s["platform"] != platform:
            continue
        out.append({
            "external_id": s["external_id"],
            "title": s["title"],
            "detail_url": s["detail_url"],
            "raw_text": s["raw_text"],
            "payload": s["payload"],
        })
    return out[:limit]


def sample_platforms() -> list[str]:
    return sorted({s["platform"] for s in all_samples()})
